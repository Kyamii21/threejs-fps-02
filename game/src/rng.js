// Deterministic randomness, in one place. The match seeds one generator per round from the
// round number, so a screenshot run with ?shot=...&seed=N replays the same bot routes and the
// same spread, and the live game just seeds from the clock. Nothing else in the game calls
// Math.random: every shuffle, jitter and coin flip goes through here, which keeps the
// simulation reproducible and the screenshot mode honest.
export function mulberry32(initial) {
  let a = initial | 0;
  return function random() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function pick(random, list) {
  return list[Math.floor(random() * list.length)];
}

export function shuffle(random, list) {
  for (let i = list.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    const tmp = list[i];
    list[i] = list[j];
    list[j] = tmp;
  }
  return list;
}
